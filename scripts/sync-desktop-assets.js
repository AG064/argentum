const fs = require('fs');
const path = require('path');
const prettier = require('prettier');
const ts = require('typescript');

const root = path.resolve(__dirname, '..');
const checkOnly = process.argv.includes('--check');

function read(relativePath) {
  return normalizeLineEndings(fs.readFileSync(path.join(root, relativePath), 'utf8'));
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/g, '\n');
}

function jsonModule(relativePath) {
  const value = JSON.parse(read(relativePath));
  return `// Generated by scripts/sync-desktop-assets.js. Do not edit.\nexport default ${JSON.stringify(value, null, 2)};\n`;
}

const i18nIndex = read('src/i18n/index.js')
  .replace("import en from './en.json';", "import en from './en.js';")
  .replace("import et from './et.json';", "import et from './et.js';");

const skillsSource = read('src/ui/desktop/modules/skills-catalog.ts');
const skillsResult = ts.transpileModule(skillsSource, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.ES2020,
    removeComments: false,
  },
  reportDiagnostics: true,
  fileName: 'skills-catalog.ts',
});

const errors = (skillsResult.diagnostics || []).filter(
  (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
);
if (errors.length > 0) {
  for (const diagnostic of errors) {
    console.error(ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'));
  }
  process.exit(1);
}

const outputs = new Map([
  ['src/ui/desktop/i18n/index.js', i18nIndex],
  ['src/ui/desktop/i18n/en.js', jsonModule('src/i18n/en.json')],
  ['src/ui/desktop/i18n/et.js', jsonModule('src/i18n/et.json')],
  [
    'src/ui/desktop/modules/skills-catalog.js',
    `// Generated by scripts/sync-desktop-assets.js. Do not edit.\n${skillsResult.outputText}`,
  ],
]);

async function synchronize() {
  const changed = [];
  for (const [relativePath, rawContent] of outputs) {
    const absolutePath = path.join(root, relativePath);
    const prettierConfig = (await prettier.resolveConfig(absolutePath)) || {};
    const content = await prettier.format(rawContent, {
      ...prettierConfig,
      filepath: absolutePath,
    });
    const current = fs.existsSync(absolutePath)
      ? normalizeLineEndings(fs.readFileSync(absolutePath, 'utf8'))
      : null;
    if (current === content) continue;
    changed.push(relativePath);
    if (!checkOnly) {
      fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
      fs.writeFileSync(absolutePath, content, 'utf8');
    }
  }

  if (checkOnly && changed.length > 0) {
    console.error(`Desktop generated assets are stale or missing:\n- ${changed.join('\n- ')}`);
    console.error('Run npm run desktop-assets:sync and commit the generated files.');
    process.exitCode = 1;
    return;
  }

  if (!checkOnly && changed.length > 0) {
    console.log(`Updated ${changed.length} desktop asset(s).`);
  }
}

synchronize().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
