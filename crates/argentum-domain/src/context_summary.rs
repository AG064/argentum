//! Lossy derived context only. Source receipts remain the outcome authority.
use std::collections::BTreeSet;

use serde::{Deserialize, Serialize};
use uuid::Uuid;

pub const MAX_SUMMARY_BYTES: usize = 8192;
pub const MAX_CHECKPOINT_BYTES: usize = 96 * 1024;
pub const MAX_COVERAGE: usize = 96;
pub const MAX_NARRATIVE_TEXT_BYTES: usize = 2048;
pub const MAX_NARRATIVE_ITEMS: usize = 24;

/// Bounded transport facts only. No provider text, reasoning or credentials.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SummaryTransportObservation {
    pub envelope_ms: u64,
    pub execution_budget_ms: u64,
    pub elapsed_ms: u64,
    pub first_event_ms: Option<u64>,
    #[serde(default)]
    pub transport_content_bytes: Option<u64>,
    #[serde(default)]
    pub retained_content_bytes: Option<u64>,
    pub terminal_event_seen: bool,
    pub valid_usage_observed: bool,
    pub usage_invalid: bool,
    pub primary_stop: String,
    pub cancellation_source: String,
    pub worker_result: String,
    pub drain_result: String,
    pub worker_settled: bool,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CompactionStatus {
    Success,
    NoOp,
    Failed,
    Deactivated,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CompactionResult {
    pub status: CompactionStatus,
    pub reason: String,
    pub checkpoint_id: Option<Uuid>,
    pub source_references: Vec<String>,
    pub before: Option<crate::context_budget::RequestAccounting>,
    pub after: Option<crate::context_budget::RequestAccounting>,
    pub summarizer_accounting: Option<crate::context_budget::RequestAccounting>,
    /// None means unknown, not zero. This usage belongs only to summarization.
    pub observed_usage: Option<crate::goal_accounting::ObservedUsage>,
}

#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SummaryNarrative {
    pub objective: String,
    pub decisions_constraints: Vec<String>,
    pub observed_changes_verification: Vec<String>,
    pub unresolved_work: Vec<String>,
    pub source_references: Vec<String>,
}

impl SummaryNarrative {
    pub fn validate(&self, expected_sources: &[SourceCoverage]) -> Result<(), &'static str> {
        let text_groups = [
            &self.decisions_constraints,
            &self.observed_changes_verification,
            &self.unresolved_work,
        ];
        if self.objective.is_empty()
            || self.objective.len() > MAX_NARRATIVE_TEXT_BYTES
            || self.objective.contains('\0')
        {
            return Err("summary format, length or source references are invalid: objective bound");
        }
        if text_groups.iter().any(|group| {
            group.len() > MAX_NARRATIVE_ITEMS
                || group.iter().any(|text| {
                    text.is_empty() || text.len() > MAX_NARRATIVE_TEXT_BYTES || text.contains('\0')
                })
        }) {
            return Err(
                "summary format, length or source references are invalid: narrative item bound",
            );
        }
        if self.source_references.len() != expected_sources.len() {
            return Err(
                "summary format, length or source references are invalid: source reference count",
            );
        }
        if self
            .source_references
            .iter()
            .zip(expected_sources)
            .any(|(reference, source)| reference != &source.identity)
        {
            return Err("summary format, length or source references are invalid: source reference identity or order");
        }
        if serde_json::to_vec(self)
            .map_err(|_| "summary serialization failed")?
            .len()
            > MAX_SUMMARY_BYTES
        {
            return Err(
                "summary format, length or source references are invalid: canonical byte bound",
            );
        }
        Ok(())
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SourceCoverage {
    pub identity: String,
    /// Digest of the permitted reconstructed source, including historical anchors.
    pub projection_sha256: String,
}

#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SummaryCheckpoint {
    pub version: u16,
    pub id: Uuid,
    pub project_id: Uuid,
    pub session_id: Uuid,
    pub budget_revision: Uuid,
    pub input_binding_sha256: String,
    pub sources: Vec<SourceCoverage>,
    pub narrative: SummaryNarrative,
    /// Generated by the host from already validated source projections, not by
    /// the summarizer. Contains no original read content or process output.
    pub evidence_anchors: Vec<serde_json::Value>,
}

impl SummaryCheckpoint {
    pub fn validate(&self) -> Result<(), &'static str> {
        let digest =
            |text: &str| text.len() == 64 && text.bytes().all(|byte| byte.is_ascii_hexdigit());
        let source_id = |text: &str| {
            let parts: Vec<_> = text.split(':').collect();
            parts.len() == 3
                && parts[0].parse::<Uuid>().is_ok_and(|id| !id.is_nil())
                && parts[1]
                    .parse::<u32>()
                    .is_ok_and(|ordinal| ordinal < crate::working_context::MAX_RUN_GROUPS)
                && matches!(parts[2], "group" | "user" | "assistant")
        };
        let mut identities = BTreeSet::new();
        if self.version != 1
            || self.id.is_nil()
            || self.project_id.is_nil()
            || self.session_id.is_nil()
            || self.budget_revision.is_nil()
            || !digest(&self.input_binding_sha256)
            || self.sources.is_empty()
            || self.sources.len() > MAX_COVERAGE
            || self.evidence_anchors.len() > MAX_COVERAGE
            || self.sources.iter().any(|source| {
                source.identity.len() > 96
                    || !source_id(&source.identity)
                    || !digest(&source.projection_sha256)
                    || !identities.insert(&source.identity)
            })
            || serde_json::to_vec(self)
                .map_err(|_| "checkpoint serialization failed")?
                .len()
                > MAX_CHECKPOINT_BYTES
        {
            return Err("invalid summary checkpoint or conflicting source coverage");
        }
        self.narrative.validate(&self.sources)
    }
}

impl std::fmt::Debug for SummaryCheckpoint {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("SummaryCheckpoint")
            .field("id", &self.id)
            .field("session_id", &self.session_id)
            .field("sources", &self.sources.len())
            .finish()
    }
}
