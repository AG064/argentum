fn run_fixture_command_with_program(root: &Path, program: &str, args: &[&str]) -> Output {
    let mut command = Command::new(program);
    command.args(args).current_dir(root).env_clear();
    for variable in [
        "SystemRoot",
        "WINDIR",
        "SystemDrive",
        "PATH",
        "TEMP",
        "TMP",
        "LOCALAPPDATA",
        "APPDATA",
        "USERPROFILE",
    ] {
        if let Some(value) = std::env::var_os(variable) {
            command.env(variable, value);
        }
    }
    let mut child = ChildGuard(
        command
            .stdin(Stdio::null())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("F10B fixture command spawn"),
    );
    let stdout = child.0.stdout.take().expect("F10B fixture stdout");
    let stderr = child.0.stderr.take().expect("F10B fixture stderr");
    let stdout_thread = std::thread::spawn(move || read_bounded(stdout));
    let stderr_thread = std::thread::spawn(move || read_bounded(stderr));
    let status = wait_for_exit(&mut child.0);
    Output {
        status,
        stdout: stdout_thread.join().expect("F10B fixture stdout reader"),
        stderr: stderr_thread.join().expect("F10B fixture stderr reader"),
    }
}

