#[test]
fn f10b_deterministic_adapter_sends_requested_generation_cap() {
    let listener = TcpListener::bind("127.0.0.1:0").expect("F10B adapter listener");
    let address = listener.local_addr().expect("F10B adapter address");
    let (request_sender, request_receiver) = std_mpsc::channel();
    let handle = std::thread::spawn(move || {
        let (mut stream, _) = listener.accept().expect("F10B adapter request");
        let request = read_http_json(&mut stream);
        request_sender.send(request).expect("F10B adapter capture");
        let body = concat!(
            "data: {\"choices\":[{\"delta\":{\"content\":\"offline\"},\"finish_reason\":\"stop\"}]}\n\n",
            "data: [DONE]\n\n"
        );
        let response = format!(
            "HTTP/1.1 200 OK\r\nContent-Type: text/event-stream\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{}",
            body.len(),
            body
        );
        stream
            .write_all(response.as_bytes())
            .expect("F10B adapter response");
    });

    let provider = OpenAiCompatibleProvider::new(
        format!("http://{address}/v1/"),
        MODEL,
        None,
        ProviderKind::OpenAiCompatible,
        "F10B deterministic adapter",
    )
    .expect("F10B deterministic provider");
    let request = ModelRequest {
        require_tool_call: false,
        continuation_scope: None,
        output_limit: 1_024,
        model: MODEL.into(),
        system: Some("Synthetic offline request-control check".into()),
        history: Vec::new(),
        prompt: "Do not call tools".into(),
        tools: Vec::new(),
        tool_exchanges: Vec::new(),
    };
    let runtime = tokio::runtime::Runtime::new().expect("F10B adapter runtime");
    let (sender, mut receiver) = tokio::sync::mpsc::channel(4);
    runtime
        .block_on(provider.stream(request, sender))
        .expect("F10B deterministic adapter stream");
    assert!(matches!(
        runtime.block_on(receiver.recv()),
        Some(ProviderEvent::Delta(text)) if text == "offline"
    ));
    assert!(matches!(
        runtime.block_on(receiver.recv()),
        Some(ProviderEvent::Completed)
    ));

    let observed = request_receiver
        .recv_timeout(Duration::from_secs(2))
        .expect("F10B adapter request receipt");
    assert_eq!(observed["max_tokens"], 1_024);
    assert_ne!(observed["max_tokens"], 196_608);
    handle.join().expect("F10B adapter server");
}

fn read_bounded(mut input: impl Read) -> Vec<u8> {
    let mut bytes = Vec::new();
    input
        .by_ref()
        .take(4 * 1024 * 1024)
        .read_to_end(&mut bytes)
        .expect("F10B child output");
    bytes
}

fn wait_for_exit(child: &mut Child) -> ExitStatus {
    let deadline = Instant::now() + Duration::from_secs(120);
    loop {
        if let Some(status) = child.try_wait().expect("F10B child status") {
            return status;
        }
        assert!(Instant::now() < deadline, "F10B CLI watchdog expired");
        std::thread::sleep(Duration::from_millis(25));
    }
}

fn assert_success(output: &Output, label: &str) {
    if output.status.success() {
        return;
    }
    let codes = String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| serde_json::from_str::<Value>(line).ok())
        .filter(|value| value["type"] == "command_failed")
        .filter_map(|value| value["code"].as_str().map(str::to_owned))
        .collect::<Vec<_>>();
    let messages = String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|line| serde_json::from_str::<Value>(line).ok())
        .filter(|value| value["type"] == "command_failed")
        .filter_map(|value| value["message"].as_str().map(str::to_owned))
        .collect::<Vec<_>>();
    panic!(
        "{label} failed with exit status; failure codes: {codes:?}; messages: {messages:?}; output: {}",
        bounded_text(output)
    );
}

