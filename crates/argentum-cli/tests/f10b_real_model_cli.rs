fn f12c_large_source(target: &str) -> Vec<u8> {
    let mut source = String::with_capacity(560 * 1024);
    source.push_str("// F12C bounded CRLF and UTF-8 fixture\r\n");
    for index in 0..8_700 {
        source.push_str(&format!(
            "// F12C filler {index:05} UTF-8 näide 中 alpha beta gamma delta\r\n"
        ));
        if index == 7_900 {
            source.push_str(target);
        }
    }
    source.push_str("pub fn fixture_tail() -> &'static str { F12C_TARGET }\r\n");
    let bytes = source.into_bytes();
    assert!(
        (500 * 1024..=600 * 1024).contains(&bytes.len()),
        "F12C fixture size was {} bytes",
        bytes.len()
    );
    bytes
}

fn crlf_preserve_large_source(target_lf: &str) -> Vec<u8> {
    let target = target_lf.replace('\n', "\r\n");
    let mut source = String::with_capacity(180 * 1024);
    source.push_str("// Large uniform CRLF and Unicode fixture\r\n");
    for index in 0..1_700 {
        source.push_str(&format!(
            "// preserved filler {index:05} näide 中 literal \\n and \\r\\n\r\n"
        ));
        if index == 1_250 {
            source.push_str(&target);
            source.push_str("\r\n");
        }
    }
    source.push_str("pub fn preserved_tail() -> &'static str { \"tail 中\" }\r\n");
    let bytes = source.into_bytes();
    assert!(bytes.len() > 64 * 1024);
    assert!(bytes
        .iter()
        .enumerate()
        .all(|(index, byte)| *byte != b'\n' || index > 0 && bytes[index - 1] == b'\r'));
    bytes
}

