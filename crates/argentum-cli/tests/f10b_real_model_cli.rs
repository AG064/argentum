fn assert_live_limits(events: &[Value]) {
    let requests = events
        .iter()
        .filter_map(|value| value["event"]["ContextRequestAccounted"].as_object())
        .collect::<Vec<_>>();
    assert!(
        !requests.is_empty(),
        "F10B typed trial had no accounted requests"
    );
    assert!(requests.len() <= 8, "F10B request allowance exceeded");

    let client_accounted_tokens = requests
        .iter()
        .map(|event| {
            let accounting = &event["accounting"];
            assert_eq!(accounting["output_reserve"], 1_024);
            accounting["accounted_input"]
                .as_u64()
                .expect("F10B accounted input")
                .saturating_add(
                    accounting["output_reserve"]
                        .as_u64()
                        .expect("F10B output reserve"),
                )
                .saturating_add(
                    accounting["uncertainty_allowance"]
                        .as_u64()
                        .expect("F10B uncertainty allowance"),
                )
        })
        .sum::<u64>();
    assert!(
        client_accounted_tokens <= 64_000,
        "F10B client-accounted allowance exceeded: {client_accounted_tokens}"
    );

    let usages = events
        .iter()
        .filter_map(|value| value["event"]["ModelUsageUpdated"].get("usage"))
        .collect::<Vec<_>>();
    let provider_usage_total = usages
        .iter()
        .map(|usage| {
            let input = usage["input_tokens"].as_u64().expect("F10B usage input");
            let output = usage["output_tokens"].as_u64().expect("F10B usage output");
            let total = usage["total_tokens"].as_u64().expect("F10B usage total");
            assert_eq!(total, input.saturating_add(output));
            assert!(output <= 1_024, "F10B provider output cap exceeded");
            total
        })
        .sum::<u64>();
    assert!(
        provider_usage_total <= 64_000,
        "F10B observed provider usage exceeded allowance: {provider_usage_total}"
    );
    println!(
        "F10B typed live accounting: requests={} client_accounted_tokens={} provider_usage_events={} provider_usage_total={} usage_available={}",
        requests.len(),
        client_accounted_tokens,
        usages.len(),
        provider_usage_total,
        !usages.is_empty()
    );
}

