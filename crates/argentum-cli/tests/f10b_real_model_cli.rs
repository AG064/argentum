impl DelegationVerifierServer {
    fn start() -> Self {
        let listener = TcpListener::bind("127.0.0.1:0").expect("F19A delegation listener");
        listener
            .set_nonblocking(true)
            .expect("F19A delegation nonblocking listener");
        let endpoint = format!(
            "http://{}/v1/",
            listener.local_addr().expect("F19A delegation address")
        );
        let requests = std::sync::Arc::new(std::sync::Mutex::new(Vec::new()));
        let recorded = requests.clone();
        let stop = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
        let stopping = stop.clone();
        let worker = std::thread::spawn(move || {
            let deadline = Instant::now() + Duration::from_secs(90);
            while !stopping.load(std::sync::atomic::Ordering::Acquire) && Instant::now() < deadline
            {
                let (mut stream, _) = match listener.accept() {
                    Ok(connection) => connection,
                    Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                        std::thread::sleep(Duration::from_millis(5));
                        continue;
                    }
                    Err(error) => panic!("F19A delegation accept: {error}"),
                };
                stream
                    .set_nonblocking(false)
                    .expect("F19A delegation blocking stream");
                stream
                    .set_read_timeout(Some(Duration::from_secs(60)))
                    .expect("F19A delegation read timeout");
                stream
                    .set_write_timeout(Some(Duration::from_secs(60)))
                    .expect("F19A delegation write timeout");
                let request = read_http_json_with_authorization(&mut stream, None);
                let index = {
                    let mut requests = recorded.lock().expect("F19A delegation request lock");
                    let index = requests.len();
                    requests.push(request.clone());
                    index
                };
                let response_body = f19a_delegation_response(index, &request);
                let response = format!(
                    "HTTP/1.1 200 OK\r\nContent-Type: text/event-stream\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{}",
                    response_body.len(),
                    response_body
                );
                stream
                    .write_all(response.as_bytes())
                    .expect("F19A delegation response");
                if index == 6 {
                    break;
                }
            }
        });
        Self {
            endpoint,
            requests,
            stop,
            worker: Some(worker),
        }
    }

    fn finish(mut self) -> Vec<Value> {
        self.stop.store(true, std::sync::atomic::Ordering::Release);
        if let Some(worker) = self.worker.take() {
            worker.join().expect("F19A delegation server worker");
        }
        std::sync::Arc::try_unwrap(self.requests)
            .expect("F19A delegation request references")
            .into_inner()
            .expect("F19A delegation request lock")
    }
}

