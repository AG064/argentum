fn assert_typed_verification_feedback(database: &Path, run_id: &str, evidence: &Value) {
    let connection = Connection::open(database).expect("F10B context database");
    let mut statement = connection
        .prepare("SELECT payload FROM context_groups WHERE run_id = ?1 ORDER BY ordinal")
        .expect("F10B context groups query");
    let groups = statement
        .query_map([run_id], |row| row.get::<_, String>(0))
        .expect("F10B context groups rows")
        .map(|row| {
            serde_json::from_str::<Value>(&row.expect("F10B context group payload"))
                .expect("F10B context group JSON")
        })
        .collect::<Vec<_>>();
    let (verify_ordinal, verify_result) = groups
        .iter()
        .find_map(|group| {
            let body = &group["body"];
            let observations = body["observations"].as_array()?;
            let observation = observations
                .iter()
                .find(|observation| observation["tool"] == "verify")?;
            Some((group["ordinal"].as_u64()?, observation["result"].clone()))
        })
        .expect("F10B persisted typed verification exchange");
    let result = verify_result
        .as_str()
        .and_then(|body| serde_json::from_str::<Value>(body).ok())
        .and_then(|value| value.as_array().and_then(|items| items.first()).cloned())
        .expect("F10B model-visible typed verification result");
    assert_eq!(result["runner"], "cargo-test-locked");
    assert_eq!(result["state"], "passed");
    assert_eq!(result["revision_after"], evidence["revision_after"]);
    assert!(groups.iter().any(|group| {
        group["ordinal"]
            .as_u64()
            .is_some_and(|ordinal| ordinal > verify_ordinal)
            && group["body"]["kind"] == "assistant"
            && group["body"]["text"]
                .as_str()
                .is_some_and(|text| !text.is_empty())
    }));
}

