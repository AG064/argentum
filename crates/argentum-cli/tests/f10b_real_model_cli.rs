fn read_http_json_with_authorization(
    stream: &mut TcpStream,
    expected_credential: Option<&str>,
) -> Value {
    read_http_json_and_body_with_authorization(stream, expected_credential).0
}

fn read_http_json_and_body_with_authorization(
    stream: &mut TcpStream,
    expected_credential: Option<&str>,
) -> (Value, Vec<u8>) {
    let mut reader = BufReader::new(stream);
    let mut first = String::new();
    reader
        .read_line(&mut first)
        .expect("F10B adapter request line");
    assert_eq!(first, "POST /v1/chat/completions HTTP/1.1\r\n");
    let mut content_length = None;
    let mut authorization = None;
    loop {
        let mut line = String::new();
        reader.read_line(&mut line).expect("F10B adapter header");
        if line == "\r\n" {
            break;
        }
        let (name, value) = line.split_once(':').expect("F10B adapter header pair");
        if name.eq_ignore_ascii_case("authorization") {
            authorization = Some(value.trim().to_owned());
        }
        if name.eq_ignore_ascii_case("content-length") {
            content_length = Some(value.trim().parse::<usize>().expect("F10B content length"));
        }
    }
    let expected_authorization =
        expected_credential.map(|credential| format!("Bearer {credential}"));
    assert!(authorization.as_deref() == expected_authorization.as_deref());
    let length = content_length.expect("F10B adapter content length");
    assert!(length <= 2 * 1024 * 1024);
    let mut body = vec![0; length];
    reader.read_exact(&mut body).expect("F10B adapter body");
    let request = serde_json::from_slice(&body).expect("F10B adapter JSON body");
    (request, body)
}

fn bounded_text(output: &Output) -> String {
    let mut text = String::from_utf8_lossy(&output.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&output.stderr));
    text.chars().take(4096).collect()
}

fn parse_json_lines(stdout: &[u8], label: &str) -> Vec<Value> {
    String::from_utf8_lossy(stdout)
        .lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| {
            serde_json::from_str(line).unwrap_or_else(|_| panic!("{label} emitted non-JSON"))
        })
        .collect()
}

