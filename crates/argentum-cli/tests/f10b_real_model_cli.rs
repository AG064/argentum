fn verifier_sse_fragmented_tool_call(id: &str, name: &str, arguments: Value) -> String {
    let arguments = arguments.to_string();
    let split = arguments.len() / 2;
    let first = verifier_sse_frame(json!({
        "choices": [{
            "delta": {
                "tool_calls": [{
                    "index": 0,
                    "id": id,
                    "type": "function",
                    "function": {
                        "name": name,
                        "arguments": &arguments[..split]
                    }
                }]
            },
            "finish_reason": null
        }]
    }));
    let second = verifier_sse_frame(json!({
        "choices": [{
            "delta": {
                "tool_calls": [{
                    "index": 0,
                    "function": {"arguments": &arguments[split..]}
                }]
            },
            "finish_reason": "tool_calls"
        }]
    }));
    format!(
        "{}{}",
        first.strip_suffix("data: [DONE]\n\n").unwrap_or(&first),
        second
    )
}

