fn replace_unique(source: &[u8], old: &str, new: &str) -> Vec<u8> {
    let source_text = std::str::from_utf8(source).expect("F10B UTF-8 fixture");
    assert_eq!(source_text.matches(old).count(), 1);
    source_text.replacen(old, new, 1).into_bytes()
}

fn list_relative_files(root: &Path) -> Vec<String> {
    let mut files = Vec::new();
    collect_files(root, root, &mut files);
    files.sort();
    files
}

fn collect_files(root: &Path, current: &Path, files: &mut Vec<String>) {
    for entry in std::fs::read_dir(current).expect("F10B directory read") {
        let entry = entry.expect("F10B directory entry");
        let path = entry.path();
        if path.file_name().and_then(|name| name.to_str()) == Some(".git") {
            continue;
        }
        if path.is_dir() {
            collect_files(root, &path, files);
        } else {
            files.push(
                path.strip_prefix(root)
                    .expect("F10B relative path")
                    .to_string_lossy()
                    .replace('\\', "/"),
            );
        }
    }
}
